// 灯带的**功耗上限** —— 默认**关闭** (跟树莓派端 led_remote.py 一致).
//
// ★ 2026-11-04 改成默认关闭, 原因 (用户要求「ESP32 跟树莓派完全一致」):
//
//   树莓派那边 (led_remote.py) **没有**任何同时点亮颗数的上限 —— 前端让点多少
//   就点多少. 固件这边原来写死 30 颗, 超了就**默默把下标大的那些灭掉** ——
//   而双色带的上灯带 (chain 176..351) 恰好是下标最大的, 于是:
//     谱子一密 (主灯带几个键 + 上灯带 6 个音 × 2 只手) → 超过 30 颗
//     → 上灯带的灯被固件悄悄灭掉 → 「上灯带不亮 / 只亮一半」
//   这正是「两条灯带行为不一致」的一大半原因.
//
//   现在默认 0 = **不限** (跟树莓派一致). 上限机制本身保留 ——
//   供电真的扛不住时可以编译时打开:
//
//     pio run -e esp32s3 --project-option "build_flags=-D LED_MAX_LIT=30"
//
//   或者在 platformio.ini 的 build_flags 里加 -D LED_MAX_LIT=30.
//
// ⚠️ 开着的风险 (跟之前一样): 整条灯带全亮 = 176 颗 × 60mA ≈ **10.5 A**,
//   供电扛不住会把板子/USB 直接拉垮 (实测板子就是这么掉线掉的).
//   树莓派那边没这个限制 —— 用户那边的供电扛得住, 所以这里默认也不限.
//
// 怎么执行 (LED_MAX_LIT > 0 时):
//   驱动在 show() 之前扫一遍像素缓冲, **点亮的颗数超过上限时, 把下标大的
//   那些灭掉** (只留下限颗). 是「颗数」上限, 不是「下标」上限 ——
//   跑马灯 (同时只亮 6 颗、从左扫到右) 完全不受影响.
#ifndef LED_LIMITS_H
#define LED_LIMITS_H

/**
 * 同时点亮的颗数上限.
 *
 *   0 = 不限 (默认, 与树莓派端 led_remote.py 一致)
 *   >0 = 超过就把下标最大的那些灭掉
 */
#ifndef LED_MAX_LIT
#define LED_MAX_LIT 0
#endif

#endif  // LED_LIMITS_H
